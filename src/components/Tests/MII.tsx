export default function MII({ test }: { test: MIITestType }) {
  ChartJS.register(
    RadarController,
    RadialLinearScale,
    PointElement,
    LineElement,
    Filler,
    Tooltip,
    Legend,
    ChartDataLabels
  );

  const toPersianDigits = (value: number | string): string => {
    return value
      .toString()
      .replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);
  };

  /* -------------------------
     1. VALUES (UNCHANGED LOGIC)
  -------------------------- */
  const xValues = ["تصویری-فضایی", "زبانی-کلامی", "درون‌فردی", " برون‌فردی", "ریاضیاتی-منطقی", "موسیقایی", "جسمی-حرکتی", "طبیعت‌گرا"];
  let yValues: number[] = [
    test.scores.VS,
    test.scores.LV,
    test.scores.Ie,
    test.scores.Ia,
    test.scores.LM,
    test.scores.M,
    test.scores.BK,
    test.scores.N,
  ];

  /* -------------------------
     2. CHART DATA & OPTIONS
  -------------------------- */
  const data = {
    labels: xValues,
    datasets: [{
      data: yValues,
      fill: true,
      tension: 0,
      backgroundColor: "rgba(33,150,243,0.3)",
      borderColor: "rgb(0,0,100)",
      borderWidth: 1,
    }]
  };

  const options: ChartOptions<'radar'> = {
    locale: 'fa-IR',
    responsive: true,
    maintainAspectRatio: false,
    layout: {
      padding: { left: 100, right: 100 }
    },
    scales: {
      r: {
        min: 0,
        suggestedMax:50,
        ticks: {
          display: false
        },
        pointLabels: {
          font: {
            family: 'Vazirmatn',
          },
        },
      },
    },
    plugins: {
      datalabels: {
        formatter: (value) => toPersianDigits(Math.round(value)),
        anchor: 'center',
        align: 'center',
        font: {
          family: 'Vazirmatn',
          weight: 'bold',
        }
      },
      legend: { display: false }
    }
  };

  /* -------------------------
     3. RENDER
  -------------------------- */
  return (
    <div className='bg-white'>
      <div style={{ height: 400 }}>
        <Radar
          data={data}
          options={options}
        />
      </div>
      <TestGuide />
    </div>
  );
}
